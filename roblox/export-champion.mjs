// Copies a validated champion's weights from a training checkpoint into Luau.
// Usage: node roblox/export-champion.mjs data/policy-training/run-XXXXXX/checkpoint.json
import { readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname } from 'node:path';
import { fileURLToPath, URL } from 'node:url';
import process from 'node:process';
import console from 'node:console';

const path = process.argv[2];
if (!path) throw new Error('Pass the path to a checkpoint.json.');
const checkpoint = JSON.parse(readFileSync(path, 'utf8'));
const { leadChampion: lead, followChampion: follow } = checkpoint;
if (!lead || !follow) throw new Error('This checkpoint has no champion.');
for (const model of [lead, follow])
  if (model.input.length !== 16 || ![30, 33].includes(model.input[0].length))
    throw new Error('Only 30- or 33-input champions are supported in Roblox.');

const list = (values) => `{ ${values.join(', ')} }`;
const model = ({ input, bias, output, priorScale }) =>
  `{
    priorScale = ${priorScale},
    bias = ${list(bias)},
    output = ${list(output)},
    input = {
${input.map((row) => `      ${list(row)},`).join('\n')}
    },
  }`;
const source = basename(dirname(path));
const out = fileURLToPath(
  new URL('./src/server/ChampionModel.luau', import.meta.url),
);
writeFileSync(
  out,
  `-- Generated by roblox/export-champion.mjs. Do not edit by hand.
return {
  source = '${source}',
  generation = ${checkpoint.generation},
  policyVersion = '${checkpoint.policyVersion}',
  lead = ${model(lead)},
  follow = ${model(follow)},
}
`,
);
console.log(`Exported ${source} (generation ${checkpoint.generation})`);
